NextMove:
	push bc
	push de
	push hl
	callfar CheckIfATMFlagIsSet
	ld a, d
	and a
	ld hl, MovedexOrder
	jr z, .notSet
	ld hl, MovedexOrderATM
.notSet
	ld b, 0
	ld c, e
	add hl, bc
	ld a, [hl]
	pop hl
	pop de
	pop bc
	ld [wd11e], a
	ret
	
